public class two_d_array {
    public static void main(String[] args) {
        int [][]X;
        X=new int[1][3];
        X[0][0]=3;
        X[0][1]=5;
        X[0][2]=7;
        System.out.println("1st "+X[0][0]);
        System.out.println("2nd "+X[0][1]);
        System.out.println("3rd "+X[0][2]);
    }
}
